#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = dirname(fileURLToPath(import.meta.url));
const CODEX_HOME = process.env.CODEX_HOME || join(homedir(), ".codex");
const AGENTS_DIR = join(CODEX_HOME, "agents");
const MARKER = "# Generated by agent-primitives/install-prose-codex.mjs.";
const MARKETPLACE = "agent-primitives";
const PLUGINS = ["prose-author", "prose-tell-scan", "prose-review"];
const AGENTS = [
  "voice-profile-render",
  "voice-draft",
  "voice-feedback-interpret",
  "prose-voice-critic",
  "prose-fidelity-critic",
  "prose-reviser",
];
const HOST_BOUNDARY = `## Codex host boundary

Run as a focused read-only custom agent. Follow only the supplied task and the primitive boundary above. Do not inspect unrelated workspace files, earlier session history, or hidden style material. Return the requested artifact or refusal to the parent agent; do not save or apply it yourself.`;

function usage() {
  console.log(`Install the complete prose toolchain for Codex.

Usage:
  node install-prose-codex.mjs
  node install-prose-codex.mjs --check
  node install-prose-codex.mjs --agents-only

Options:
  --check        Verify the three plugins and six generated custom agents.
  --agents-only  Install or check custom agents without changing plugins.
  --help         Show this help.

Set CODEX_HOME to use a non-default Codex configuration directory.`);
}

function parseArgs(argv) {
  const known = new Set(["--check", "--agents-only", "--help", "-h"]);
  const unknown = argv.filter((arg) => !known.has(arg));
  if (unknown.length) throw new Error(`unknown option: ${unknown[0]}`);
  return {
    agentsOnly: argv.includes("--agents-only"),
    check: argv.includes("--check"),
    help: argv.includes("--help") || argv.includes("-h"),
  };
}

function readPrimitive(name) {
  const source = join(REPO, "primitives", "agents", name, "agent.md");
  const text = readFileSync(source, "utf8");
  const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) throw new Error(`${source}: expected YAML frontmatter`);

  const field = (key) => {
    const found = match[1].match(new RegExp(`^${key}:\\s*(.+)$`, "m"));
    if (!found) throw new Error(`${source}: missing ${key}`);
    return found[1].trim();
  };
  const sourceName = field("name");
  if (sourceName !== name) throw new Error(`${source}: name is ${sourceName}, expected ${name}`);

  return { description: field("description"), name, prompt: match[2].trim() };
}

function renderAgent(name) {
  const primitive = readPrimitive(name);
  const instructions = `${primitive.prompt}\n\n${HOST_BOUNDARY}\n`;
  return `${MARKER}\nname = ${JSON.stringify(primitive.name)}\ndescription = ${JSON.stringify(primitive.description)}\nsandbox_mode = "read-only"\ndeveloper_instructions = ${JSON.stringify(instructions)}\n`;
}

function runCodex(args) {
  const result = spawnSync("codex", args, { encoding: "utf8" });
  if (result.error?.code === "ENOENT") throw new Error("codex was not found on PATH");
  if (result.status !== 0) {
    const detail = (result.stderr || result.stdout || "unknown error").trim();
    throw new Error(`codex ${args.join(" ")} failed: ${detail}`);
  }
  return result.stdout;
}

function installPlugins() {
  runCodex([
    "plugin",
    "marketplace",
    "add",
    "ConnorBritain/agent-primitives",
    "--ref",
    "main",
    "--json",
  ]);
  for (const plugin of PLUGINS) {
    runCodex(["plugin", "add", `${plugin}@${MARKETPLACE}`, "--json"]);
    console.log(`  plugin ${plugin}`);
  }
}

function installAgents() {
  mkdirSync(AGENTS_DIR, { recursive: true });
  for (const name of AGENTS) {
    const target = join(AGENTS_DIR, `${name}.toml`);
    const rendered = renderAgent(name);
    if (existsSync(target)) {
      const current = readFileSync(target, "utf8");
      const generatedWithoutMarker = rendered.slice(MARKER.length + 1);
      if (!current.startsWith(`${MARKER}\n`) && current !== generatedWithoutMarker) {
        throw new Error(`${target} already exists and was not generated by this installer`);
      }
    }
    writeFileSync(target, rendered, { encoding: "utf8", mode: 0o600 });
    console.log(`  agent  ${name}`);
  }
}

function checkPlugins() {
  const listing = JSON.parse(runCodex(["plugin", "list", "--json"]));
  for (const name of PLUGINS) {
    const plugin = listing.installed?.find(
      (item) => item.pluginId === `${name}@${MARKETPLACE}`,
    );
    if (!plugin?.installed || !plugin?.enabled) {
      throw new Error(`${name}@${MARKETPLACE} is not installed and enabled`);
    }
    console.log(`  plugin ${name}  OK`);
  }
}

function checkAgents() {
  for (const name of AGENTS) {
    const target = join(AGENTS_DIR, `${name}.toml`);
    if (!existsSync(target)) throw new Error(`${target} is missing`);
    if (readFileSync(target, "utf8") !== renderAgent(name)) {
      throw new Error(`${target} differs from the current primitive source`);
    }
    console.log(`  agent  ${name}  OK`);
  }
}

export { AGENTS, HOST_BOUNDARY, MARKER, parseArgs, readPrimitive, renderAgent };

try {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    usage();
  } else if (options.check) {
    if (!options.agentsOnly) checkPlugins();
    checkAgents();
    console.log("\nCodex prose installation is current.");
  } else {
    if (!options.agentsOnly) installPlugins();
    installAgents();
    console.log(`\nInstalled the Codex prose toolchain. Start a new Codex session to load it.`);
  }
} catch (error) {
  console.error(`install-prose-codex: ${error.message}`);
  process.exitCode = 1;
}
